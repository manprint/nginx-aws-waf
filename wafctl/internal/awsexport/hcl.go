package awsexport

import (
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// snakeSpecial are the names a plain CamelCase → snake_case split gets wrong for the provider.
var snakeSpecial = map[string]string{
	"IPSetReferenceStatement":  "ip_set_reference_statement",
	"IPAddressVersion":         "ip_address_version",
	"ARN":                      "arn",
	"CloudWatchMetricsEnabled": "cloudwatch_metrics_enabled",
}

// singular names the repeated block of an array-of-objects member.
var singular = map[string]string{
	"rules":                 "rule",
	"rule_action_overrides": "rule_action_override",
	"text_transformations":  "text_transformation",
	"statements":            "statement",
}

var reCamel = regexp.MustCompile(`([a-z0-9])([A-Z])`)

func snake(k string) string {
	if s, ok := snakeSpecial[k]; ok {
		return s
	}
	return strings.ToLower(reCamel.ReplaceAllString(k, "${1}_${2}"))
}

// hclString quotes s (strconv.Quote escaping) and escapes template sequences.
func hclString(s string) string {
	q := strconv.Quote(s)
	q = strings.ReplaceAll(q, "${", "$${")
	return strings.ReplaceAll(q, "%{", "%%{")
}

var reTFName = regexp.MustCompile(`[^A-Za-z0-9_]`)

func tfName(s string) string {
	n := reTFName.ReplaceAllString(s, "_")
	if n == "" || (n[0] >= '0' && n[0] <= '9') {
		n = "_" + n
	}
	return n
}

// expr is an unquoted HCL expression.
type expr string

type hclWriter struct {
	sb     strings.Builder
	ipsets map[string]string // ARN → tf resource name
}

func (w *hclWriter) line(depth int, format string, a ...any) {
	w.sb.WriteString(strings.Repeat("  ", depth))
	fmt.Fprintf(&w.sb, format, a...)
	w.sb.WriteByte('\n')
}

func (w *hclWriter) scalar(k string, v any) string {
	switch x := v.(type) {
	case expr:
		return string(x)
	case string:
		if k == "ARN" {
			if n, ok := w.ipsets[x]; ok {
				return "aws_wafv2_ip_set." + n + ".arn"
			}
		}
		return hclString(x)
	case bool:
		return strconv.FormatBool(x)
	case int:
		return strconv.Itoa(x)
	case []string:
		q := make([]string, len(x))
		for i, s := range x {
			q[i] = hclString(s)
		}
		return "[" + strings.Join(q, ", ") + "]"
	}
	panic(fmt.Sprintf("hcl: unsupported value %T for %s", v, k))
}

// body writes the members of an object: attributes (aligned like terraform fmt) then blocks, each sorted.
func (w *hclWriter) body(depth int, m M) {
	var attrs, blocks []string
	for k, v := range m {
		switch v.(type) {
		case M, []M:
			blocks = append(blocks, k)
		default:
			attrs = append(attrs, k)
		}
	}
	sort.Slice(attrs, func(a, b int) bool { return attrOrder(attrs[a]) < attrOrder(attrs[b]) })
	sort.Strings(blocks)
	width := 0
	for _, k := range attrs {
		width = max(width, len(snake(k)))
	}
	for _, k := range attrs {
		w.line(depth, "%-*s = %s", width, snake(k), w.scalar(k, m[k]))
	}
	for _, k := range blocks {
		name := snake(k)
		switch v := m[k].(type) {
		case M:
			w.block(depth, name, v)
		case []M:
			if s, ok := singular[name]; ok {
				name = s
			}
			for _, e := range v {
				w.block(depth, name, e)
			}
		}
	}
}

// attrOrder keeps name/priority first, then alphabetical.
func attrOrder(k string) string {
	switch k {
	case "Name":
		return "0"
	case "Priority":
		return "1"
	}
	return "2" + snake(k)
}

func (w *hclWriter) block(depth int, name string, m M) {
	if len(m) == 0 {
		w.line(depth, "%s {}", name)
		return
	}
	w.line(depth, "%s {", name)
	w.body(depth+1, m)
	w.line(depth, "}")
}

// HCL renders the document as a self-contained Terraform module.
func HCL(d *Document, region string) ([]byte, error) {
	if region == "" {
		region = "eu-central-1"
	}
	w := &hclWriter{ipsets: map[string]string{}}
	acl := d.WebACL
	aclTF := tfName(acl["Name"].(string))
	for _, ip := range d.IPSets {
		n := ip["Name"].(string)
		w.ipsets[ipSetARNFromName(acl, n)] = tfName(n)
	}
	w.line(0, "# Generated by wafctl export-aws for web ACL %s. Do not edit: re-export instead.", acl["Name"])
	for _, s := range d.ManualSteps {
		if s != stepIPSetARNs {
			w.line(0, "# manual step: %s", s)
		}
	}
	for _, l := range d.Lossy {
		w.line(0, "# lossy (not exported): %s", l)
	}
	w.sb.WriteString(`
terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 6.0"
    }
  }
}

`)
	w.line(0, "provider \"aws\" {")
	w.line(1, "region = %s", hclString(region))
	w.line(0, "}")
	w.sb.WriteString(`
variable "alb_arn" {
  type    = string
  default = ""
}
`)
	for _, ip := range d.IPSets {
		w.sb.WriteByte('\n')
		w.line(0, "resource \"aws_wafv2_ip_set\" %q {", tfName(ip["Name"].(string)))
		w.body(1, ip)
		w.line(0, "}")
	}
	w.sb.WriteByte('\n')
	w.line(0, "resource \"aws_wafv2_web_acl\" %q {", aclTF)
	w.body(1, acl)
	w.line(0, "}")
	w.sb.WriteString(`
resource "aws_wafv2_web_acl_association" "this" {
  count        = var.alb_arn == "" ? 0 : 1
  resource_arn = var.alb_arn
`)
	w.line(1, "web_acl_arn  = aws_wafv2_web_acl.%s.arn", aclTF)
	w.line(0, "}")
	return []byte(w.sb.String()), nil
}

// ipSetARNFromName finds the placeholder ARN used in acl for the IP set name.
func ipSetARNFromName(acl M, name string) string {
	var found string
	var walk func(v any)
	walk = func(v any) {
		switch x := v.(type) {
		case M:
			for k, e := range x {
				if s, ok := e.(string); ok && k == "ARN" && strings.Contains(s, "/ipset/"+name+"/") {
					found = s
				}
				walk(e)
			}
		case []M:
			for _, e := range x {
				walk(e)
			}
		}
	}
	walk(acl)
	return found
}
